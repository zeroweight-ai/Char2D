import { expect,test } from "@playwright/test";
test("confirms action deletion, rebuilds without idle, and deletes the character",async({page,request})=>{
  const created=await request.post("/api/characters",{multipart:{mode:"prompt",name:`Delete test ${Date.now()}`,description:"green knight",viewType:"side_scroller"}});
  expect(created.status()).toBe(202);const {id}=await created.json();
  await page.goto(`/characters/${id}`);await expect(page.getByRole("heading",{name:"Your transparent character sheet"})).toBeVisible({timeout:30_000});
  await page.getByRole("button",{name:"Looks good — accept sheet"}).click();await expect(page.getByTestId("hero-status")).toHaveText("Ready to play",{timeout:30_000});
  await page.getByRole("tab",{name:"Moves"}).click();
  await page.getByRole("button",{name:"Delete Walk",exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Cancel",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Walk",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Delete Idle",exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Delete permanently",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Idle",exact:true})).toHaveCount(0);
  await expect(page.getByTestId("hero-status")).toHaveText("Ready to play",{timeout:30_000});
  await page.getByRole("tab",{name:"Play"}).click();
  await expect(page.getByRole("button",{name:"Walk",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Idle",exact:true})).toHaveCount(0);
  await expect(page.getByTestId("sprite-player")).toHaveAttribute("data-action","walk");
  const stage=page.getByRole("group",{name:"Animation stage, keyboard controls"});await stage.focus();await page.keyboard.press("KeyD");await expect(page.getByTestId("sprite-player")).toHaveAttribute("data-action","walk");
  await page.getByRole("tab",{name:"Moves"}).click();
  await page.getByRole("button",{name:"Delete Walk",exact:true}).click();await page.getByRole("dialog").getByRole("button",{name:"Delete permanently",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Walk",exact:true})).toHaveCount(0);
  await expect(page.getByTestId("hero-status")).toHaveText("Ready to play",{timeout:30_000});
  await page.getByRole("tab",{name:"Play"}).click();
  await expect(page.getByRole("button",{name:"Walk",exact:true})).toHaveCount(0);
  await expect(page.getByTestId("sprite-player")).toHaveAttribute("data-action","jump");
  const detail=await (await request.get(`/api/characters/${id}`)).json();expect(detail.manifest.actions.walk).toBeUndefined();expect(detail.manifest.actions.idle).toBeUndefined();
  const sheetAsset=detail.sheet.processedAssetId;
  await page.getByRole("button",{name:"Delete character",exact:true}).click();await page.getByRole("dialog").getByRole("button",{name:"Delete permanently",exact:true}).click();
  await expect(page).toHaveURL("/");expect((await request.get(`/api/characters/${id}`)).status()).toBe(404);expect((await request.get(`/api/assets/${sheetAsset}`)).status()).toBe(404);
});
test("deletes a character from the gallery only after confirmation",async({page,request})=>{
  const name=`Gallery delete ${Date.now()}`;
  const response=await request.post("/api/characters",{multipart:{mode:"prompt",name,description:"green knight",viewType:"top_down"}});const {id}=await response.json();
  await page.goto(`/characters/${id}`);await expect(page.getByRole("heading",{name:"Your transparent character sheet"})).toBeVisible({timeout:30_000});
  await page.goto("/");
  const card=page.getByRole("article").filter({has:page.getByRole("heading",{name,exact:true})});
  await card.getByRole("button",{name:"Delete character",exact:true}).click();await page.getByRole("dialog").getByRole("button",{name:"Cancel",exact:true}).click();await expect(card).toBeVisible();
  await card.getByRole("button",{name:"Delete character",exact:true}).click();await page.getByRole("dialog").getByRole("button",{name:"Delete permanently",exact:true}).click();
  await expect(card).toHaveCount(0);expect((await request.get(`/api/characters/${id}`)).status()).toBe(404);
});
